<?php

use PHPUnit\Framework\TestCase;

require_once 'db/postgresql/PostgresqlDatabase.class.php';

class PostgresqlIntegrationTest extends TestCase {
    protected function setUp(): void {
        parent::setUp();
        $this->assertSame('1', getenv('KLOUDSPEAKER_POSTGRES_INTEGRATION'), 'Use the isolated postgres-tests Compose service');
    }

    private function connectAdapter($database = 'kloudspeaker_test', $password = "fixture'pg\\password") {
        return PostgresqlDatabase::createFromConf(array(
            'host' => 'postgres', 'user' => 'migration_test', 'password' => $password,
            'database' => $database, 'table_prefix' => 'migration_', 'charset' => 'UTF8',
        ));
    }

    private function createFixture() {
        $database = $this->connectAdapter();
        $database->queries('CREATE TEMPORARY TABLE migration_contract (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label TEXT NULL, amount NUMERIC(20,4) NULL)');
        return $database;
    }

    public function testConnectionAndAdapterMetadata(): void {
        $database = $this->connectAdapter();
        $this->assertTrue($database->isConnected());
        $this->assertTrue($database->databaseExists());
        $this->assertSame('postgresql', $database->type());
        $this->assertSame("fixture'pg\\password", $database->password());
        $this->assertSame('migration_items', $database->table('items'));
        $database->selectDb();
        $database->setCharset('UTF8');
        $this->assertSame('UTF8', $database->query('SHOW client_encoding')->value());
    }

    public function testUnicodeNullsDecimalsAndIdentity(): void {
        $database = $this->createFixture();
        $label = "caf\xc3\xa9 'quoted' \\ path \xf0\x9f\x98\x80";
        $this->assertSame(1, $database->update('INSERT INTO migration_contract (label, amount) VALUES (' . $database->string($label, true) . ', 1234567890123456.7890)'));
        $this->assertSame('1', (string) $database->lastId());
        $row = $database->query('SELECT id, label, amount FROM migration_contract')->firstRow();
        $this->assertSame('1', $row['id']);
        $this->assertSame($label, $row['label']);
        $this->assertSame('1234567890123456.7890', $row['amount']);
        $this->assertSame(1, $database->update('INSERT INTO migration_contract (label) VALUES (' . $database->string(null, true) . ')'));
        $this->assertNull($database->query('SELECT label FROM migration_contract WHERE id=2')->firstValue('label'));
        $this->assertSame("''", $database->string('', true));
        $this->assertSame("'0'", $database->string('0', true));
        $this->assertSame("'a''b',NULL,'0'", $database->arrayString(array("a'b", null, '0'), true));
    }

    public function testRowsCountsAndLookupHelpers(): void {
        $database = $this->createFixture();
        $database->queries("INSERT INTO migration_contract (label) VALUES ('one'); INSERT INTO migration_contract (label) VALUES ('two')");
        $result = $database->query('SELECT id, label FROM migration_contract ORDER BY id');
        $this->assertSame(2, $result->count());
        $this->assertSame(array(array('id' => '1', 'label' => 'one'), array('id' => '2', 'label' => 'two')), $result->rows());
        $result->free();
        $this->assertSame(array('one', 'two'), $database->query('SELECT label FROM migration_contract ORDER BY id')->values('label'));
        $this->assertSame(array(1 => 'one', 2 => 'two'), $database->query('SELECT id, label FROM migration_contract ORDER BY id')->valueMap('id', 'label'));
        $this->assertSame(array('one' => array(array('label' => 'one')), 'two' => array(array('label' => 'two'))), $database->query('SELECT label FROM migration_contract ORDER BY id')->listMap('label'));
        $this->assertSame('two', $database->query('SELECT id, label FROM migration_contract ORDER BY id')->value(1, 1));
    }

    public function testEmptyResultSentinels(): void {
        $database = $this->createFixture();
        $this->assertSame(0, $database->query('SELECT * FROM migration_contract')->count());
        $this->assertSame(array(), $database->query('SELECT * FROM migration_contract')->rows());
        $this->assertNull($database->query('SELECT * FROM migration_contract')->firstRow());
        $this->assertNull($database->query('SELECT label FROM migration_contract')->firstValue('label'));
        $this->assertNull($database->query('SELECT label FROM migration_contract')->value());
    }

    public function testFailedQueryRequiresRollback(): void {
        $database = $this->createFixture();
        $database->startTransaction();
        $database->startTransaction();
        $this->assertTrue($database->isTransaction());
        $database->update("INSERT INTO migration_contract (label) VALUES ('rolled back')");
        try {
            $database->query('SELECT * FROM missing_migration_table');
            $this->fail('A missing table must produce a service error');
        } catch (ServiceException $exception) {
            $this->assertSame('INVALID_CONFIGURATION', $exception->type());
            $this->assertTrue($database->isTransaction());
        }
        try {
            $database->commit();
            $this->fail('An aborted transaction must not be reported as committed');
        } catch (ServiceException $exception) {
            $this->assertSame('INVALID_CONFIGURATION', $exception->type());
        } finally {
            $database->rollback();
        }
        $this->assertFalse($database->isTransaction());
        $this->assertSame('0', $database->query('SELECT COUNT(*) AS total FROM migration_contract')->firstValue('total'));
    }

    public function testCommitAndIndependentConnections(): void {
        $database = $this->createFixture();
        $other = $this->createFixture();
        $database->startTransaction();
        $database->update("INSERT INTO migration_contract (label) VALUES ('committed')");
        $this->assertFalse($other->isTransaction());
        $database->commit();
        $this->assertFalse($database->isTransaction());
        $this->assertSame('committed', $database->query('SELECT label FROM migration_contract')->firstValue('label'));
        $this->assertSame('0', $other->query('SELECT COUNT(*) AS total FROM migration_contract')->firstValue('total'));
    }

    public function testConnectionFailuresAreControlledAndDoNotExposePasswords(): void {
        foreach (array(array('missing_migration_database', "fixture'pg\\password"), array('kloudspeaker_test', "invalid'fixture\\password")) as $credentials) {
            try {
                $this->connectAdapter($credentials[0], $credentials[1]);
                $this->fail('Invalid database credentials must not connect');
            } catch (ServiceException $exception) {
                $this->assertSame('INVALID_CONFIGURATION', $exception->type());
                $this->assertStringNotContainsString($credentials[1], $exception->details());
            }
        }
    }

    public function testMultiQueryFailureRemainsControlled(): void {
        $database = $this->createFixture();
        try {
            $database->queries("INSERT INTO migration_contract (label) VALUES ('first'); SELECT * FROM missing_migration_table");
            $this->fail('Multi-query failures must produce a service error');
        } catch (ServiceException $exception) {
            $this->assertSame('INVALID_CONFIGURATION', $exception->type());
        }
        $this->assertSame('0', $database->query('SELECT COUNT(*) AS total FROM migration_contract')->firstValue('total'));
    }

    public function testApplicationErrorHandlerPreservesServiceErrors(): void {
        $database = $this->createFixture();
        set_error_handler(function ($severity, $message, $file, $line) {
            throw new ErrorException($message, 0, $severity, $file, $line);
        });
        try {
            try {
                $database->query('SELECT * FROM missing_migration_table');
                $this->fail('SQL warnings must become service errors, not escape the adapter');
            } catch (ServiceException $exception) {
                $this->assertSame('INVALID_CONFIGURATION', $exception->type());
            }
            try {
                $this->connectAdapter('kloudspeaker_test', 'invalid-handler-fixture-password');
                $this->fail('Connection warnings must become service errors');
            } catch (ServiceException $exception) {
                $this->assertSame('INVALID_CONFIGURATION', $exception->type());
                $this->assertStringNotContainsString('invalid-handler-fixture-password', $exception->details());
            }
        } finally {
            restore_error_handler();
        }
    }
}